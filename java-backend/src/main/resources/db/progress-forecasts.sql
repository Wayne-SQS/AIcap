CREATE TABLE IF NOT EXISTS progress_forecasts (
  id bigint NOT NULL AUTO_INCREMENT,
  project_id varchar(20) NOT NULL,
  history_start date NOT NULL,
  history_end date NOT NULL,
  observed_days int NOT NULL,
  tasks_total int NOT NULL,
  tasks_open int NOT NULL,
  tasks_done int NOT NULL,
  recent_completions int NOT NULL,
  completions_per_week decimal(8,2) NULL,
  estimated_remaining_days int NULL,
  estimated_date date NULL,
  forecast_status varchar(20) NOT NULL,
  assumptions varchar(500) NOT NULL,
  requested_by int NOT NULL,
  requested_at datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  decided_by int NULL,
  decided_at datetime NULL,
  decision_note varchar(200) NULL,
  record_status varchar(16) NOT NULL DEFAULT 'proposed',
  PRIMARY KEY (id),
  KEY idx_progress_forecasts_project (project_id,requested_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
